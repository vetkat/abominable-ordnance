local Forces = require("core.forces")

describe("the force rules", function()
  it("keep peace between the tamed force and player forces", function()
    assert.is_true(Forces.cease_fire("player"))
    assert.is_true(Forces.cease_fire("team-2"))
  end)

  it("keep the tamed force at war with the natives", function()
    assert.is_false(Forces.cease_fire("enemy"))
  end)

  it("leave the neutral force and the tamed force alone", function()
    assert.is_nil(Forces.cease_fire("neutral"))
    assert.is_nil(Forces.cease_fire("ao-tamed"))
  end)

  it("let a researched force or the tamed force earn nest loot", function()
    assert.is_true(Forces.earns_loot("player", true))
    assert.is_false(Forces.earns_loot("player", false))
    assert.is_true(Forces.earns_loot("ao-tamed", false))
  end)

  it("let the landing blast hit only forces at war, never the tamed force", function()
    assert.is_true(Forces.blast_hits("enemy", "player", true))
    assert.is_true(Forces.blast_hits("team-2", "player", true))
    assert.is_false(Forces.blast_hits("player", "player", true))
    assert.is_false(Forces.blast_hits("player", "team-2", false))
    assert.is_false(Forces.blast_hits("ao-tamed", "player", true))
    assert.is_false(Forces.blast_hits("neutral", "player", false))
    assert.is_false(Forces.blast_hits("neutral", "player", true))
  end)

  it("count only the natives when the launcher is gone", function()
    assert.is_true(Forces.blast_hits("enemy", nil, false))
    assert.is_false(Forces.blast_hits("player", nil, true))
    assert.is_false(Forces.blast_hits("ao-tamed", nil, true))
    assert.is_false(Forces.blast_hits("neutral", nil, true))
  end)

  it("leave the pair of the tamed and the feral force to the feral rule", function()
    assert.is_nil(Forces.cease_fire("ao-feral"))
  end)

  it("put the feral force at war with every force but neutral and itself", function()
    assert.is_false(Forces.feral_cease_fire("enemy"))
    assert.is_false(Forces.feral_cease_fire("player"))
    assert.is_false(Forces.feral_cease_fire("ao-tamed"))
    assert.is_false(Forces.feral_cease_fire("some-scenario-force"))
    assert.is_nil(Forces.feral_cease_fire("neutral"))
    assert.is_nil(Forces.feral_cease_fire("ao-feral"))
  end)

  it("give no nest loot for kills of the feral force", function()
    assert.is_false(Forces.earns_loot("ao-feral", false))
  end)
end)
