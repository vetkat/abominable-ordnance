local Balance = require("core.balance")
local Names = require("core.names")

describe("the stasis names and numbers", function()
  it("name the ward, its research and the recipe prefixes", function()
    assert.are.equal("ao-stasis-ward", Names.WARD)
    assert.are.equal("ao-stasis-ward", Names.STASIS_TECH)
    assert.are.equal("ao-warded-", Names.WARDED)
    assert.are.equal("ao-ward-", Names.PACK)
    assert.are.equal("ao-unward-", Names.UNPACK)
  end)

  it("slow the spoil timer 20 times and price the ward", function()
    local s = Balance.stasis
    assert.are.equal(20, s.factor)
    assert.are.equal(1, s.pack_time)
    assert.are.same({ stack = 50, time = 2, plastic = 2, steel = 1, circuit = 1 }, s.ward)
    assert.are.same({ count = 150, time = 30 }, s.research)
  end)
end)
